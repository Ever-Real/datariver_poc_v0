function cases(category, expectedPrimaryMode, expectedIntent, entityResolutionRequired, acceptableFallback, queries) {
  return queries.map((entry, index) => {
    const [query, negativePair] = Array.isArray(entry) ? entry : [entry, undefined]
    return {
      id: `${category.toLowerCase()}-${String(index + 1).padStart(2, '0')}`,
      category,
      query,
      expected_primary_mode: expectedPrimaryMode,
      expected_intent: expectedIntent,
      entity_resolution_required: entityResolutionRequired,
      acceptable_fallback: acceptableFallback,
      ...(negativePair ? { negative_pair: negativePair } : {}),
    }
  })
}

